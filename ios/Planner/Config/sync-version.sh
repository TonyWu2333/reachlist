#!/bin/sh
# OPEN-11=A：版本号单一来源为项目根 package.json，与 Web / Android 同源。
# 生成 Version.xcconfig，供 Signing.xcconfig include。
# 本脚本同时被 App target 的 Run Script 构建阶段调用，保持版本自动同步。
#
# ── 布局无关 + 仓库边界内查找 ──────────────────────────────────────────
# 本脚本在两种仓库布局下都可能出现：
#   上游 planner          → <仓库根>/ios/Planner/Config/sync-version.sh
#   独立仓库 reachlist-ios → <仓库根>/Planner/Config/sync-version.sh
# 两者的仓库根深度不同，因此**不能**把上溯层数写死（原写法 ../../.. 在独立
# 仓库里会越过仓库根、落到父目录去找 package.json → MODULE_NOT_FOUND）。
#
# 解决办法：从脚本所在目录逐级向上查找 package.json，并以**仓库根（含 .git
# 的目录）为硬边界**——一旦越出仓库就停止，绝不跨仓库抓到别人的 package.json。
# 这样既适配两种布局，也天然满足「独立仓库自足、不依赖上游」的要求。
set -eu

OUT="$(dirname "$0")/Version.xcconfig"

DIR="$(cd "$(dirname "$0")" && pwd)"
ROOT=""
d="$DIR"
while true; do
  if [ -f "$d/package.json" ]; then ROOT="$d"; break; fi
  # 已到仓库根仍未命中 → 本仓库不含 package.json，停止上溯
  if [ -e "$d/.git" ]; then break; fi
  d="$(dirname "$d")"
  # 兜底：走到文件系统根还没找到 .git 就退出，避免死循环
  if [ "$d" = "/" ]; then break; fi
done

if [ -z "$ROOT" ]; then
  # 本仓库不含 package.json（理论上不应发生：两仓都应自带），
  # 此时保留已提交的 Version.xcconfig 原值，不让版本同步阶段中断构建。
  if [ -f "$OUT" ]; then
    echo "sync-version: 未找到 package.json，沿用已提交的 $(basename "$OUT")（跳过版本同步）"
    exit 0
  fi
  echo "sync-version: 未找到 package.json，且无 $(basename "$OUT") 可沿用" >&2
  exit 1
fi
PKG="${ROOT}/package.json"

# ── 解析 version ────────────────────────────────────────────────────────
# 不强依赖 node：Xcode Run Script 阶段的 PATH 不保证包含 node（本机 node 装在
# ~/.workbuddy/binaries/… 下，构建阶段未必可见）。因此：
#   有 node → 用 node 解析 JSON（权威、含 JSON 转义处理）
#   无 node → 退回 POSIX sed 解析 "version" 字段（覆盖本项目实际格式）
# 两条路径产出必须一致。
VERSION=""
if command -v node >/dev/null 2>&1; then
  VERSION="$(node -p "JSON.parse(require('fs').readFileSync(process.argv[1],'utf8')).version" "$PKG")"
else
  # POSIX sed 兜底：取第一个 "version": "x.y.z" 形式的值。
  # 顶层 version 出现在 dependencies 之前，head -1 保证取到顶层那个。
  VERSION="$(sed -n 's/.*"version"[[:space:]]*:[[:space:]]*"\([^"]*\)".*/\1/p' "$PKG" | head -1)"
fi

if [ -z "$VERSION" ]; then
  echo "sync-version: 无法从 ${PKG} 解析 version" >&2
  exit 1
fi

# ── 计算 CURRENT_PROJECT_VERSION ────────────────────────────────────────
# 与 android/app/build.gradle:21 一致：versionCode = major*10000 + minor*100 + patch
# 与 planner/src 侧语义保持一致；独立仓库无 android 目录，但公式同源。
CORE="$(printf '%s' "$VERSION" | sed 's/[^0-9.]*$//')"   # 去掉 1.2.3-beta.4 的后缀
MAJOR="$(printf '%s' "$CORE" | cut -d. -f1)"
MINOR="$(printf '%s' "$CORE" | cut -d. -f2)"
PATCH="$(printf '%s' "$CORE" | cut -d. -f3)"
: "${MINOR:=0}"
: "${PATCH:=0}"
: "${MAJOR:=0}"

if [ "$MINOR" -ge 100 ] || [ "$PATCH" -ge 100 ]; then
  echo "sync-version: minor/patch must be < 100 (version=${VERSION})" >&2
  exit 1
fi

CODE=$((MAJOR * 10000 + MINOR * 100 + PATCH))

cat > "${OUT}" <<EOF
// Generated by sync-version.sh — DO NOT EDIT.
// Source: package.json (${VERSION}). OPEN-11=A / android/app/build.gradle:21.
MARKETING_VERSION = ${VERSION}
CURRENT_PROJECT_VERSION = ${CODE}
EOF

echo "sync-version: MARKETING_VERSION=${VERSION} CURRENT_PROJECT_VERSION=${CODE}"
